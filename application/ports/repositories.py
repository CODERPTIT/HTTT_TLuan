from pathlib import Path
from typing import Protocol

from domain.interaction.interaction import Interaction, InteractionType
from domain.customer.customer import Customer
from domain.product.product import Product
from domain.search.search_query import SearchQuery


class ProductRepositoryPort(Protocol):
    def findById(self, productId: int) -> Product: ...
    def findRelevant(self, query: SearchQuery | None) -> list[Product]: ...
    def findEligibleProducts(self) -> list[Product]: ...
    def updateStock(self, product: Product) -> None: ...
    def saveImage(self, content: bytes, filename: str, content_type: str) -> str: ...
    def cropImage(self, reference: str, box: list[float]) -> str: ...
    def imagePath(self, reference: str) -> Path: ...
    def indexVector(self, productId: int, vector: list[float]) -> None: ...
    def searchVectors(self, vector: list[float]) -> list[tuple[int, float]]: ...


class InteractionRepositoryPort(Protocol):
    def findByCustomer(self, customerId: int) -> list[Interaction]: ...
    def listAll(self) -> list[Interaction]: ...
    def record(self, customerId: int, product: Product, kind: InteractionType) -> None: ...


class CustomerRepositoryPort(Protocol):
    def findById(self, customerId: int) -> Customer: ...
